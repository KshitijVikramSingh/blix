"""Generate the golden values the engine's test (Blix.Test.Graphics Section BZ) holds its C# EON twin to.

    uv run python tools/generate_eon_golden.py          # writes src/Blix.Test.Graphics/fixtures/eon_golden.json
    uv run python tools/generate_eon_golden.py --check  # fails if it is stale (tests/test_generated_golden.py runs this)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

LAB = Path(__file__).resolve().parents[1]
REPO = LAB.parents[1]
sys.path.insert(0, str(LAB))

from bsdflab import eon  # noqa: E402

OUT = REPO / "src/Blix.Test.Graphics/fixtures/eon_golden.json"
RHOS = [[0.2, 0.5, 0.9], [1.0, 1.0, 1.0], [0.05, 0.3, 0.6]]
ROUGHNESS = [0.0, 0.2, 0.5, 0.8, 1.0]
ANGLES = [  # (mu_i, mu_o, azimuth difference)
    (0.9, 0.9, 0.0), (0.9, 0.9, 3.14159265), (0.5, 0.5, 0.0), (0.5, 0.5, 1.5707963), (0.2, 0.7, 2.5), (0.7, 0.2, 0.4),
    (0.05, 0.9, 1.0), (0.9, 0.05, 1.0), (0.3, 0.3, 3.14159265), (1.0, 0.6, 0.0), (0.1, 0.1, 0.0), (0.6, 0.35, 1.2),
]
ALBEDO_MU = [0.05, 0.2, 0.5, 0.8, 1.0]


def render() -> str:
    cases = []
    for rho in RHOS:
        for r in ROUGHNESS:
            for mu_i, mu_o, phi in ANGLES:
                si, so = np.sqrt(1 - mu_i ** 2), np.sqrt(1 - mu_o ** 2)
                wi, wo = np.array([si * np.cos(phi), si * np.sin(phi), mu_i]), np.array([so, 0.0, mu_o])
                f = np.pi * eon.f_eon(np.array(rho), r, wi, wo)
                cases.append({"rho": rho, "r": r, "n_dot_l": mu_i, "n_dot_v": mu_o, "l_dot_v": float(f"{np.dot(wi, wo):.9g}"),
                              "pi_f": [float(f"{v:.9g}") for v in f]})
    albedos = []
    for rho in RHOS:
        for r in ROUGHNESS:
            for mu in ALBEDO_MU:
                albedos.append({"rho": rho, "r": r, "n_dot_v": mu, "albedo": [float(f"{v:.9g}") for v in eon.albedo_closed_form(np.array(rho), r, mu)]})
    hemi = []
    for rho in RHOS:
        for r in ROUGHNESS:
            hemi.append({"rho": rho, "r": r, "hemispherical_albedo": [float(f"{v:.9g}") for v in eon.hemispherical_albedo(np.array(rho), r)]})
    return json.dumps({"what": "GENERATED by lab/bsdf/tools/generate_eon_golden.py from bsdflab/eon.py. Do not edit by hand.",
                       "f_eon_times_pi": cases, "albedo": albedos, "hemispherical_albedo": hemi}, indent=1) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(REPO), f"({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
