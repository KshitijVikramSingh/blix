import numpy as np
import pytest

from tmlab import exposure


def _frame(seed=0, n=48):
    rng = np.random.default_rng(seed)
    f = np.exp(rng.normal(np.log(0.15), 1.2, size=(n, n, 3)))
    f[:4, :4] = 30.0  # a few bright pixels
    return f


def test_histogram_is_normalised():
    h = exposure.log_histogram(_frame())
    assert h.sum() == pytest.approx(1.0) and np.all(h >= 0)


def test_metering_is_exposure_equivariant():
    # Scale a frame by 2^u (u on the bin grid): the predicted exposure moves by exactly -u.
    frame = _frame()
    p = exposure.MeteringParams()
    base = exposure.meter(exposure.log_histogram(frame), p)
    for u in (-2.0, 1.0, 3.0):
        assert exposure.meter(exposure.log_histogram(frame * 2.0 ** u), p) == pytest.approx(base - u, abs=0.26)


def test_proxy_target_is_exposure_equivariant():
    frame = _frame()
    e0 = exposure.best_exposure(frame[::2, ::2])
    e1 = exposure.best_exposure(frame[::2, ::2] * 4.0)  # two stops brighter -> two stops less exposure
    assert e1 == pytest.approx(e0 - 2.0, abs=0.3)


def test_dark_frame_gets_more_exposure_than_a_bright_one():
    dark, bright = _frame() * 0.02, _frame() * 5.0
    assert exposure.best_exposure(dark[::2, ::2]) > exposure.best_exposure(bright[::2, ::2])


def test_flat_black_frame_does_not_produce_nan():
    h = exposure.log_histogram(np.zeros((8, 8, 3)))
    assert np.isfinite(exposure.meter(h, exposure.MeteringParams()))


def test_fit_recovers_a_known_model():
    # Targets generated BY the model with known parameters must be recoverable to a small error.
    truth = exposure.MeteringParams(dark_cut=-5.0, bright_cut=3.0, key=-2.0, protect=4.0)
    hists = [exposure.log_histogram(_frame(s) * 2.0 ** (s % 5 - 2)) for s in range(16)]
    targets = np.array([exposure.meter(h, truth) for h in hists])
    p = exposure.fit_metering(hists, targets, starts=6)
    assert exposure.rms([exposure.meter(h, p) for h in hists], targets) < 0.15


def test_labels_override_the_proxy(tmp_path):
    from tmlab import capture
    capture.write_pfm(tmp_path / "a__dim__z1.pfm", np.full((16, 16, 3), 0.2, np.float32), {"scene": "a"})
    frames = exposure.load_frames(tmp_path, labels={"a__dim__z1": 1.25})
    assert frames[0][3] == 1.25
